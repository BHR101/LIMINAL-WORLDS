// Dev helper: verify the signature set pieces and portal views render.
import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto('http://localhost:5173/');
await page.waitForFunction(() => window.liminal?.engine?.mode === 'menu', null, { timeout: 60000 });
const place = (id, opts) => page.evaluate(([id, opts]) => window.liminal.engine.debugPlace(id, opts), [id, opts]);
const shot = async (name, wait = 2500) => { await page.waitForTimeout(wait); await page.screenshot({ path: `scripts/.out/sp-${name}.png` }); };
await place('sunken-cathedral', { position: [56, -0.4, -30], yaw: -Math.PI / 2 }); await shot('chapel');
await place('infinite-ascent', { position: [108, 13.5, 0], yaw: -Math.PI / 2, pitch: 0.05 }); await shot('penrose');
await place('infinite-ascent', { position: [0, 9.5, -111], yaw: 0, pitch: 0.1 }); await shot('high-arch');
await place('impossible-house', { position: [6.5, 0, -1008], yaw: -Math.PI / 2 }); await shot('turned');
await place('impossible-house', { position: [-7.6, 0, -1007.6], yaw: Math.PI / 2 }); await shot('window');
await place('obsidian-city', { position: [-116.5, 0, -40], yaw: Math.PI / 2 }); await shot('panel');
await place('last-horizon', { position: [0, 0, -440], yaw: 0 });
await page.evaluate(() => { const e = window.liminal.engine; e.player.position.z = -444; });
await shot('reveal-a', 6000);
await shot('reveal-b', 12000);
await browser.close();
